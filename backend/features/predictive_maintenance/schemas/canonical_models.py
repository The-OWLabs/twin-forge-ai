"""Canonical Industrial Data Models (Senseye Inspired).

Standardizes heterogeneous entities from PLC/SCADA, CMMS, MES, and ERP systems
into a unified enterprise asset hierarchy with explicit data provenance and financial tracking.
"""
from datetime import datetime, date
from enum import Enum
from typing import Any, Optional
from pydantic import BaseModel, Field


class DataProvenance(str, Enum):
    """Explicitly tracks data origin to ensure synthetic data is never represented as actual."""
    ACTUAL = "ACTUAL"          # Ingested from real industrial systems / edge gateways
    SIMULATED = "SIMULATED"    # Generated by physical simulation / fallback models
    ESTIMATED = "ESTIMATED"    # Output of ML predictions or financial models
    REALIZED = "REALIZED"      # Verified post-maintenance outcome savings


class AssetCriticality(str, Enum):
    A = "A"  # Production-Critical / Bottleneck station (zero redundant capacity)
    B = "B"  # Major Line asset (buffer capacity available)
    C = "C"  # Balance of Plant (low production impact)


class SourceSystemType(str, Enum):
    PLC_SCADA = "PLC_SCADA"
    CMMS_MAXIMO = "CMMS_MAXIMO"
    MES_OPCENTER = "MES_OPCENTER"
    ERP_SAP = "ERP_SAP"
    CSV_SFTP_DROP = "CSV_SFTP_DROP"
    MQTT_GATEWAY = "MQTT_GATEWAY"


class RecommendationUrgency(str, Enum):
    IMMEDIATE = "IMMEDIATE"                    # Action required within 4-8 hours
    SCHEDULED_NEXT_SHIFT = "SCHEDULED_NEXT_SHIFT"  # Action within 24 hours
    SCHEDULED_WEEKLY = "SCHEDULED_WEEKLY"      # Routine planned maintenance
    MONITOR = "MONITOR"                        # Close observation; no intervention yet


class ApprovalStatus(str, Enum):
    PENDING_APPROVAL = "PENDING_APPROVAL"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    EXECUTED = "EXECUTED"


class RoiEntryType(str, Enum):
    AVOIDED_DOWNTIME = "AVOIDED_DOWNTIME"
    UNPLANNED_STOPPAGE = "UNPLANNED_STOPPAGE"
    PREVENTIVE_REPAIR = "PREVENTIVE_REPAIR"
    PLATFORM_OPERATING_COST = "PLATFORM_OPERATING_COST"


# 1. DimAsset
class DimAsset(BaseModel):
    asset_id: str = Field(..., description="Canonical enterprise asset ID (e.g. CNC-001)")
    asset_name: str
    plant_id: str
    line_id: str
    equipment_type: str
    criticality: AssetCriticality
    manufacturer: Optional[str] = None
    model_number: Optional[str] = None
    installation_date: Optional[date] = None
    rated_speed_rpm: float = 1800.0
    rated_power_kw: float = 45.0
    baseline_vibration_rms: float = 1.2
    baseline_temperature_c: float = 42.0
    hourly_downtime_cost_usd: float = Field(2500.0, description="Downtime loss per hour of stoppage")
    replacement_value_usd: float = Field(150000.0, description="Asset replacement capital cost")
    is_active: bool = True
    created_at: datetime = Field(default_factory=datetime.utcnow)
    updated_at: datetime = Field(default_factory=datetime.utcnow)


# 2. BridgeAssetSourceId
class BridgeAssetSourceId(BaseModel):
    bridge_id: str
    canonical_asset_id: str
    source_system: SourceSystemType
    source_identifier: str
    description: Optional[str] = None
    mapped_at: datetime = Field(default_factory=datetime.utcnow)
    is_primary: bool = True


# 3. FactSensorReading
class FactSensorReading(BaseModel):
    reading_id: str
    asset_id: str
    timestamp: datetime
    vibration_mm_s: float
    temperature_celsius: float
    pressure_bar: Optional[float] = None
    motor_current_amps: Optional[float] = None
    torque_nm: Optional[float] = None
    rpm: float
    operating_hours: float
    data_provenance: DataProvenance
    source_system: str
    ingestion_timestamp: datetime = Field(default_factory=datetime.utcnow)
    lineage_job_id: Optional[str] = None


# 4. FactMachineState
class FactMachineState(BaseModel):
    state_id: str
    asset_id: str
    state_start: datetime
    state_end: Optional[datetime] = None
    duration_seconds: Optional[float] = None
    operating_state: str  # RUNNING, IDLE, MICRO_STOP, UNPLANNED_DOWNTIME, PLANNED_MAINTENANCE
    state_reason: Optional[str] = None
    source_system: str
    data_provenance: DataProvenance


# 5. FactWorkOrder
class FactWorkOrder(BaseModel):
    work_order_id: str
    asset_id: str
    source_work_order_num: str
    work_order_type: str  # PREVENTIVE, CORRECTIVE, EMERGENCY, INSPECTION
    failure_code: Optional[str] = None
    failure_description: Optional[str] = None
    work_status: str      # OPEN, IN_PROGRESS, COMPLETED, CANCELLED
    scheduled_start: Optional[datetime] = None
    actual_start: Optional[datetime] = None
    actual_finish: Optional[datetime] = None
    labor_hours: float = 0.0
    labor_rate_usd: float = 75.0
    spare_parts_cost_usd: float = 0.0
    total_cost_usd: float = 0.0
    technician_notes: Optional[str] = None
    source_system: str
    data_provenance: DataProvenance


# 6. FactProductionDowntime
class FactProductionDowntime(BaseModel):
    downtime_id: str
    asset_id: str
    line_id: str
    start_time: datetime
    end_time: datetime
    duration_minutes: float
    downtime_category: str  # UNPLANNED_MECHANICAL, ELECTRICAL, PROCESS_JAM, CHANGEOVER
    lost_production_units: int
    downtime_financial_impact_usd: float
    root_cause_asset_id: Optional[str] = None
    source_system: str
    data_provenance: DataProvenance


# 7. FactInventoryCost
class FactInventoryCost(BaseModel):
    inventory_record_id: str
    part_number: str
    asset_id: str
    part_description: str
    stock_on_hand: int
    safety_stock: int
    unit_cost_usd: float
    lead_time_days: int
    supplier_id: Optional[str] = None
    last_replenished_at: Optional[datetime] = None
    data_provenance: DataProvenance


# 8. FactMachinePrediction
class FactMachinePrediction(BaseModel):
    prediction_id: str
    asset_id: str
    prediction_timestamp: datetime
    prediction_horizon_hours: int
    anomaly_score: float = Field(..., ge=0.0, le=1.0, description="Unsupervised sensor residual deviation")
    failure_probability: float = Field(..., ge=0.0, le=1.0, description="Supervised failure likelihood within horizon")
    risk_category: str     # LOW, MEDIUM, HIGH, CRITICAL
    criticality_adjusted_risk_index: float = Field(..., description="CARI = P_fail * CriticalityWeight * HourlyLoss")
    contributing_features: dict[str, Any]
    model_version: str
    data_provenance: DataProvenance = DataProvenance.ESTIMATED


# 9. FactMaintenanceRecommendation
class FactMaintenanceRecommendation(BaseModel):
    recommendation_id: str
    asset_id: str
    created_at: datetime = Field(default_factory=datetime.utcnow)
    urgency: RecommendationUrgency
    recommended_action: str
    rationale: str
    supporting_evidence: dict[str, Any]
    expected_downtime_avoided_hours: float
    expected_cost_avoidance_usd: float
    required_parts: list[str] = Field(default_factory=list)
    parts_available: bool = True
    approval_status: ApprovalStatus = ApprovalStatus.PENDING_APPROVAL
    approved_by: Optional[str] = None
    approved_at: Optional[datetime] = None
    cmms_work_order_created: Optional[str] = None


# 10. FactMaintenanceOutcome
class FactMaintenanceOutcome(BaseModel):
    outcome_id: str
    recommendation_id: str
    asset_id: str
    verified_at: datetime
    verification_outcome: str  # TRUE_POSITIVE_PREVENTED, FALSE_POSITIVE_EARLY, MISSED_FAILURE
    actual_downtime_hours_avoided: float
    actual_maintenance_cost_usd: float
    verified_by: str
    findings: Optional[str] = None


# 11. FactRoiLedger
class FactRoiLedger(BaseModel):
    ledger_id: str
    asset_id: str
    recorded_at: datetime = Field(default_factory=datetime.utcnow)
    entry_type: RoiEntryType
    value_category: DataProvenance  # ESTIMATED or REALIZED
    amount_usd: float
    downtime_hours: float
    calculation_formula: str
    evidence_reference: str
    cumulative_net_benefit_usd: float
